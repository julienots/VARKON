const Diag = {
  make(code, params = [], where = null) {
    const e = ERRORS[code] || { level: 'error', title: code, why: '', fix: '' };
    const fill = (s) => String(s || '').replace(/\{(\d+)\}/g, (_, i) => params[i] ?? '');
    return { code, level: e.level, title: fill(e.title), why: fill(e.why), fix: fill(e.fix), where };
  },
  hasErrors(list) { return list.some((d) => d.level === 'error'); },
  catalog: ERRORS,
};
